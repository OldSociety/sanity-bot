  let serial=0
  const click=()=>({id:`special-ui-${++serial}`,guildId:'g',user:{id:'p'},customId:`snow:p:battle-special:${started.battle.fightId}`,isButton:()=>true,deferUpdate:async()=>{},editReply:async p=>frames.push(p),reply:async p=>frames.push(p)})
  pending=true
