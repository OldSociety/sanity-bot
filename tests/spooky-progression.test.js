const test = require('node:test')
const assert = require('node:assert/strict')
const Sequelize = require('sequelize')
const defineUser = require('../Models/User/User')
const migration = require('../migrations/20261001000000-create-spooky-core')
const { defineSpookyModels } = require('../services/spooky/models')
const { createEconomy } = require('../services/spooky/economy')
const { createParticipants } = require('../services/spooky/participants')
const { createActions } = require('../services/spooky/actions')
const { createProgression } = require('../services/spooky/progression')
const { config } = require('../services/spooky/config')

async function fixture(t, { eligible = true, bank = 0, random = () => .2 } = {}) {
  const sequelize = new Sequelize({ dialect: 'sqlite', storage: ':memory:', logging: false })
  t.after(() => sequelize.close())
  const User = defineUser(sequelize, Sequelize.DataTypes); await User.sync()
  await migration.up(sequelize.getQueryInterface())
  const models = defineSpookyModels(sequelize), event = { ...config, enabled: true }
  const economy = createEconomy({ sequelize, models, configVersion: event.version, clock: () => new Date(event.startsAt) })
  const participants = createParticipants({ models, economy, event })
  const progression = createProgression({ User, models, event, isUnwanted: () => eligible })
  const handlers = progression.wrapHandlers({ sweet_tooth: async () => ({ roleQueued: true }), lost_candy: async () => ({ noEffect: 'lost' }),
    steal_candy: async () => ({ stolen: 1 }), curse_distribute_two: async () => ({ deliveredCandy: 2 }), standard_gift: async () => ({ noEffect: 'no_recipient' }) })
  const actions = createActions({ models, participants, economy, event, handlers, random, getCurseState: () => false })
  const input = key => ({ eventId: event.eventId, guildId: 'guild', actorId: 'alice', interactionId: key, action: 'treat' })
  await participants.register(input('register'))
  const user = await User.create({ user_id: 'alice', user_name: 'Alice', bank, fate_points: 99 })
  const run = (key, fn) => economy.execute({ ...input(key), operationType: 'progression_test' }, fn)
  return { User, models, economy, event, participants, progression, actions, user, input, run }
}

test('configured host stays last and unranked across pages without displacing other players or winning', async t => {
  const f = await fixture(t), event = { ...f.event, competition: { nonCompetitiveUserIds: ['alice'] } }
  await f.run('host-high-score', ctx => f.progression.prestige(ctx, { actorId: 'alice', action: 'treat', outcome: 'sweet_tooth' }, { crownWon: true }))
  for (let index = 0; index < 11; index++) {
    const userId = `member${index}`
    await f.participants.register({ ...f.input(`reg-${userId}`), actorId: userId })
    await f.User.create({ user_id: userId, user_name: userId })
    await f.run(`score-${userId}`, ctx => f.progression.prestige(ctx, { actorId: userId, action: 'treat', outcome: 'standard_gift' }, {}))
  }
  const read = require('../services/spooky/leaderboard').createLeaderboard({ models: f.models, economy: f.economy, User: f.User, event })
  const scope = { eventId: event.eventId, guildId: 'guild' }
  const first = await read(scope), last = await read(scope, 2)
  assert.equal(first.length, 10); assert.ok(first.every(row => row.userId !== 'alice' && row.rank === 1))
  assert.equal(last.at(-1).userId, 'alice'); assert.equal(last.at(-1).rank, null); assert.equal(last.at(-1).nonCompetitive, true)
  assert.equal((await f.models.Participant.findOne({ where: { userId: 'alice' } })).treatPrestige, 12)
  const closingEconomy = createEconomy({ sequelize: f.User.sequelize, models: f.models, clock: () => new Date(event.endsAt) })
  const snapshots = require('../services/spooky/winner-snapshot').createWinnerSnapshot({ models: f.models, event })
  const frozen = await closingEconomy.execute({ ...scope, actorId: 'system', workerKey: 'host-proof', operationType: 'test' }, snapshots.freeze)
  const operation = await f.models.Operation.findByPk(frozen.receipt.operationId)
  assert.equal(operation.receipt.tracks.overall.entrants.some(row => row.userId === 'alice'), false)
  assert.equal(operation.receipt.tracks.overall.userIds.length, 11)
})

test('caller crown win credits five fate for any registered player, caps bank and adds ten prestige once', async t => {
  const f = await fixture(t, { eligible: false, bank: 98 })
  const handlers = f.progression.wrapHandlers({ sweet_tooth: async () => ({ crownWon: true, awardedUserId: 'alice' }) })
  const result = await f.run('new-crown', ctx => handlers.sweet_tooth(ctx, { actorId: 'alice', action: 'treat', outcome: 'sweet_tooth' }))
  assert.equal(result.receipt.fateBonus, 2); assert.equal((await f.user.reload()).bank, 100)
  assert.equal(result.receipt.prestige.delta, 12)
  assert.equal(result.receipt.bankBefore, 98)
  assert.equal(result.receipt.bank, 100)
  assert.equal(result.receipt.fatePoints, 99)
  await f.user.update({ bank: 50, fate_points: 60 })
  const replay = await f.run('new-crown', () => { throw new Error('no second award') })
  assert.equal(replay.receipt.bankBefore, 98)
  assert.equal(replay.receipt.bank, 100)
  assert.equal(replay.receipt.fatePoints, 99)
  assert.equal(replay.receipt.prestige.delta, 12)
  assert.equal((await f.models.Participant.findOne()).treatPrestige, 12)
})

