test('failure costs prestige, target no-effect scores zero, and bank/scoring failures roll back action candy', async t => {
  const lost = await fixture(t, { random: () => 0 })
  await lost.actions.execute(lost.input('lost'))
  assert.equal((await lost.models.Participant.findOne()).treatPrestige, -1)
  const empty = await fixture(t, { random: () => .6 })
  await empty.actions.execute(empty.input('empty'))
  assert.equal((await empty.models.Participant.findOne()).treatPrestige, 0)
  const missing = await fixture(t)
  await missing.user.destroy()
  await assert.rejects(() => missing.actions.execute(missing.input('missing')), /account/)
  assert.equal((await missing.models.Participant.findOne()).candy, 10)
  const provisional = createProgression({ ...lost, event: { ...lost.event, prestige: { ...config.prestige, status: 'provisional' } }, isUnwanted: () => true })
  await assert.rejects(() => lost.run('provisional', ctx => provisional.prestige(ctx, { action: 'treat', actorId: 'alice', outcome: 'standard_gift' }, {})), /provisional/)
})
