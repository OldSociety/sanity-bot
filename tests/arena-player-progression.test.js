const test = require('node:test'), assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { createPlayerProgression } = require('../services/arena/player-progression')
const guild = '111111111111111111', player = '222222222222222222', other = '333333333333333333'
test('a single persisted player level defaults to1, advances atomically and replays without granting twice', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'arena-player-level-')), file = path.join(directory, 'levels.json')
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  const progression = createPlayerProgression({ file })
  assert.deepEqual(await progression.get(guild, player), { level: 1, xp: 0, revision: 0, xpRewardsEnabled: false })
  assert.equal(fs.existsSync(file), false)
  const first = await progression.advanceLevel(guild, player, 5, { operationId: 'future-award-1', reason: 'isolated foundation test' })
  assert.equal(first.level, 5)
  const before = fs.readFileSync(file, 'utf8')
  assert.deepEqual(await progression.advanceLevel(guild, player, 5, { operationId: 'future-award-1', reason: 'isolated foundation test' }), first)
  assert.equal(fs.readFileSync(file, 'utf8'), before)
  assert.equal((await createPlayerProgression({ file }).get(guild, player)).level, 5)
  assert.equal((await progression.get(guild, other)).level, 1)
  await assert.rejects(progression.advanceLevel(guild, player, 6, { operationId: 'future-award-1', reason: 'isolated foundation test' }), /already used/)
  await assert.rejects(progression.advanceLevel(guild, player, 4, { operationId: 'lower', reason: 'invalid decrease' }), /cannot lower/)
  await assert.rejects(progression.advanceLevel(guild, player, 61, { operationId: 'cap', reason: 'invalid cap' }), /Invalid/)
  assert.equal(fs.readFileSync(file, 'utf8'), before)
  const record = JSON.parse(before)
  assert.equal(Object.keys(record.players).length, 1)
  assert.equal(record.players[`${guild}:${player}`].characters, undefined)
})
test('serialized progression updates preserve other players and corrupted data is never reset', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'arena-player-level-')), file = path.join(directory, 'levels.json')
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  const progression = createPlayerProgression({ file })
  await Promise.all([
    progression.advanceLevel(guild, player, 2, { operationId: 'p1', reason: 'isolated test' }),
    progression.advanceLevel(guild, other, 3, { operationId: 'p2', reason: 'isolated test' }),
  ])
  assert.equal((await progression.get(guild, player)).level, 2)
  assert.equal((await progression.get(guild, other)).level, 3)
  fs.writeFileSync(file, '{broken')
  await assert.rejects(progression.get(guild, player))
  await assert.rejects(progression.advanceLevel(guild, player, 4, { operationId: 'never', reason: 'cannot reset corruption' }))
  assert.equal(fs.readFileSync(file, 'utf8'), '{broken')
})
